// Create a program that takes a number from 1 to 4 and prints the season using multiple cases together:




let num = 3;

switch (num) {
    case 1:
        console.log("Winter");
        break;
    case 2:
        console.log("Winter");
        break;
    case 3:
        console.log("Summer");
        break;
    case 4:
        console.log("Summer");
        break;
    default:
        console.log("Invalid Number");
        break;
}