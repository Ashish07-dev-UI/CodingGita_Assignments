// Write a program that checks a character and prints whether it is a vowel or consonant using switch.




let char = "u";

switch (char) {
    case "a":
        console.log("Vowel");
        break;
    case "e":
        console.log("Vowel");
        break;
    case "i":
        console.log("Vowel");
        break;
    case "o":
        console.log("Vowel");
        break;
    case "u":
        console.log("Vowel");
        break;
    default:
        console.log("Consonant")
        break;
}